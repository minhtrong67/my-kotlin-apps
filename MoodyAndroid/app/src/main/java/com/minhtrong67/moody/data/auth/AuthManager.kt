package com.minhtrong67.moody.data.auth

import android.content.Context
import android.util.Log
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import com.minhtrong67.moody.data.AppUser
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.tasks.await

/**
 * Wraps Firebase Auth + Google sign-in (Credential Manager). When Firebase isn't configured
 * (no google-services.json) everything degrades gracefully to "signed out / guest only".
 */
class AuthManager(private val appContext: Context, val firebaseReady: Boolean) {
    private val _user = MutableStateFlow<AppUser?>(null)
    val user: StateFlow<AppUser?> = _user.asStateFlow()

    private val _initializing = MutableStateFlow(firebaseReady)
    val initializing: StateFlow<Boolean> = _initializing.asStateFlow()

    init {
        if (firebaseReady) {
            FirebaseAuth.getInstance().addAuthStateListener { auth ->
                _user.value = auth.currentUser?.let {
                    AppUser(it.uid, it.displayName, it.email, it.photoUrl?.toString())
                }
                _initializing.value = false
            }
        }
    }

    /** The OAuth *web* client id generated by the google-services plugin from google-services.json. */
    private fun webClientId(): String? {
        val id = appContext.resources.getIdentifier("default_web_client_id", "string", appContext.packageName)
        return if (id != 0) appContext.getString(id) else null
    }

    /** @param activityContext must be an Activity context (the account picker is shown over it). */
    suspend fun signInWithGoogle(activityContext: Context): Result<Unit> {
        if (!firebaseReady) return Result.failure(IllegalStateException("Firebase is not configured"))
        val clientId = webClientId()
            ?: return Result.failure(IllegalStateException("default_web_client_id missing – enable Google sign-in in Firebase and re-download google-services.json"))
        return runCatching {
            val option = GetSignInWithGoogleOption.Builder(clientId).build()
            val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
            val result = CredentialManager.create(activityContext).getCredential(activityContext, request)
            val cred = result.credential
            check(cred is CustomCredential && cred.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                "Unexpected credential type"
            }
            val google = GoogleIdTokenCredential.createFrom(cred.data)
            FirebaseAuth.getInstance()
                .signInWithCredential(GoogleAuthProvider.getCredential(google.idToken, null))
                .await()
            Unit
        }.onFailure { Log.w("Moody", "Google sign-in failed", it) }
    }

    fun signOut() {
        if (firebaseReady) FirebaseAuth.getInstance().signOut()
    }
}
